import { createRequire } from 'node:module';
const puppeteer = createRequire('/tmp/e2e/')('puppeteer-core');
const b = await puppeteer.launch({ executablePath: '/usr/bin/chromium-browser', args: ['--no-sandbox','--disable-gpu','--disable-dev-shm-usage','--host-resolver-rules=MAP localhost host.docker.internal'] });
const p = await b.newPage(); p.setDefaultTimeout(60000); p.setDefaultNavigationTimeout(120000);
await p.setViewport({ width: 1400, height: 1000 });
p.on('pageerror', (e) => console.log('pageerror', e.message));
p.on('console', (m) => { if (m.type()==='error') console.log('console', m.text().slice(0,200)); });
p.on('response', async (r) => { if (r.request().method()!=='GET' || r.url().includes('login') || r.url().includes('reset-password')) console.log(r.request().method(), r.status(), r.url().replace(/reset-password\/[^?]+/,'reset-password/<t>').slice(0,90), r.headers()['location']?.slice(0,70) ?? ''); });
await p.goto(process.env.LINK, { waitUntil: 'networkidle2' });
await p.waitForSelector('#password_confirmation');
await p.type('#password', 'reset-password-99');
await p.type('#password_confirmation', 'reset-password-99');
console.log('before', await p.$eval('#password', e=>e.value.length), await p.$eval('#password_confirmation', e=>e.value.length));
await p.click('.auth-submit');
await new Promise((r)=>setTimeout(r,25000));
console.log('path', await p.evaluate(()=>location.pathname), '| errors', await p.$$eval('.field-error', e=>e.map(x=>x.textContent)), '| success', await p.$$eval('.form-success', e=>e.map(x=>x.textContent)), '| title', await p.$eval('.auth-form h2', e=>e.textContent));
console.log('fields', await p.$$eval('.auth-form input', e=>e.map(x=>x.id)));
await p.screenshot({ path: '/out/r.png' });
await b.close();
